//! aria-contracts — قراردادهای عمومی کرنل آریا.
//!
//! این کریت میزبان انواع، تریت‌ها، اسکیماها و تعریف‌های نسخه‌بندی عمومی است
//! که همه موتورها و پلاگین‌ها موظف به استفاده از آن هستند. این کریت هیچ
//! منطق کسب‌وکاری ندارد؛ فقط قراردادها را تعریف می‌کند.
//!
//! ## ماژول‌ها
//!
//! - `command`: پاکت دستور (Command Envelope)
//! - `event`: پاکت رویداد (Event Envelope)
//! - `manifest`: قرارداد مانیفست پلاگین و اسکیمای JSON آن
//! - `rpc`: قرارداد RPC پلاگین (JSON-RPC 2.0، دفترچه روش‌ها، نشانه نشست)
//! - `services`: تریت‌های سرویس‌های کرنل
//! - `error`: قرارداد خطا (محدوده کدها و ساختار خطای RPC)
//! - `versioning`: سیاست نسخه‌بندی و کمک‌کننده‌های سازگاری

pub mod command;
pub mod error;
pub mod event;
pub mod manifest;
pub mod rpc;
pub mod services;
pub mod versioning;
